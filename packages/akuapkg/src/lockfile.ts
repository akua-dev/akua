import { Effect, Option, Schema } from "effect"
import * as TOML from "smol-toml"
import { LockInvalid } from "./errors"
import { table, tables, toToml } from "./toml-write"

/**
 * `akua.lock`, the machine-maintained lockfile (docs/lockfile-format.md):
 * one `[[package]]` per resolved dependency, alphabetical, each pinned by
 * digest. The rules of the previous release's `akua_core::lock_file`.
 */

export const LOCK_VERSION = 1

const LockedPackage = Schema.Struct({
  name: Schema.String,
  version: Schema.String,
  /** `oci://…`, `git+https://…@<ref>`, `helm+<repo>#<chart>` or `path+file://…`. */
  source: Schema.String,
  /** `sha256:` for OCI, Helm and path dependencies; `git:<commit>` for git. */
  digest: Schema.String,
  vendor_digest: Schema.optionalKey(Schema.String),
  signature: Schema.optionalKey(Schema.String),
  dependencies: Schema.optionalKey(Schema.Array(Schema.String)),
  attestation: Schema.optionalKey(Schema.String),
  replaced: Schema.optionalKey(Schema.Struct({ path: Schema.String })),
  yanked: Schema.optionalKey(Schema.Boolean),
  kyverno_source_digest: Schema.optionalKey(Schema.String),
  converter_version: Schema.optionalKey(Schema.String),
  /** A CRD dependency's generated `.akua/crds/<dep>/` tree, as `lock` wrote it. */
  crds_digest: Schema.optionalKey(Schema.String)
})
export type LockedPackage = typeof LockedPackage.Type

const Lock = Schema.Struct({
  version: Schema.Number,
  package: Schema.optionalKey(Schema.Array(LockedPackage))
})
export type Lock = typeof Lock.Type

const decodeLock = Schema.decodeUnknownEffect(Lock)

/** Parse and validate `akua.lock` text; `path` names the file in errors. */
export const parseLock = Effect.fn("parseLock")(function*(text: string, path: string) {
  const invalid = (message: string) => new LockInvalid({ path, message })
  const raw = yield* Effect.try({
    try: (): unknown => TOML.parse(text),
    catch: (cause) => invalid(`toml parse error: ${cause instanceof Error ? cause.message : String(cause)}`)
  })
  const lock = yield* decodeLock(raw).pipe(Effect.mapError((error) => invalid(`toml parse error: ${error.message}`)))
  if (lock.version !== LOCK_VERSION) {
    return yield* invalid(
      `unsupported lockfile version ${lock.version}; this akua understands version ${LOCK_VERSION}`
    )
  }
  const packages = lock.package ?? []
  for (const [index, entry] of packages.entries()) {
    const previous = packages[index - 1]
    if (previous !== undefined && entry.name < previous.name) {
      return yield* invalid(
        `package entries must be alphabetical by name; \`${entry.name}\` comes before \`${previous.name}\``
      )
    }
    if (previous !== undefined && entry.name === previous.name && entry.version === previous.version) {
      return yield* invalid(`package \`${entry.name}\` appears multiple times at the same version`)
    }
    if (!entry.digest.startsWith("sha256:") && !entry.digest.startsWith("git:")) {
      return yield* invalid(
        `package \`${entry.name}\`: digest must start with \`sha256:\` (OCI/path dep) or \`git:\` (git dep)`
      )
    }
  }
  return lock
})

/** The entries whose digests a fetch must reproduce: every pinned remote source, or only OCI blobs. */
export const pinnedEntries = (lock: Lock, ociOnly = false): ReadonlyArray<LockedPackage> =>
  (lock.package ?? []).filter((entry) =>
    ociOnly ? entry.source.startsWith("oci://") : !entry.source.startsWith("path+file://")
  )

export const emptyLock: Lock = { version: LOCK_VERSION, package: [] }

/**
 * The header names the verbs as the invoking CLI spells them (`akuapkg add`,
 * or `akua pkg add` embedded). The previous release always wrote `akua add`,
 * a command neither CLI has.
 */
const lockHeader = (cli: string) =>
  "# akua.lock - machine-maintained. Never hand-edit.\n" +
  `# Regenerated by \`${cli} add\`, \`${cli} pull\`, \`${cli} publish\`, \`${cli} update\`.\n\n`

const byNameThenVersion = (a: LockedPackage, b: LockedPackage) =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : a.version > b.version ? 1 : 0

/** The lockfile body as the previous release serialized it, entries sorted; no header. */
export const lockBody = (lock: Lock) =>
  toToml(table([
    ["version", lock.version],
    [
      "package",
      tables((lock.package ?? []).toSorted(byNameThenVersion).map((entry) =>
        table([
          ["name", entry.name],
          ["version", entry.version],
          ["source", entry.source],
          ["digest", entry.digest],
          ["vendor_digest", entry.vendor_digest],
          ["signature", entry.signature],
          ["dependencies", entry.dependencies === undefined || entry.dependencies.length === 0 ? undefined : entry.dependencies],
          ["attestation", entry.attestation],
          ["replaced", entry.replaced && table([["path", entry.replaced.path]])],
          ["yanked", entry.yanked],
          ["kyverno_source_digest", entry.kyverno_source_digest],
          ["converter_version", entry.converter_version],
          ["crds_digest", entry.crds_digest]
        ])
      ))
    ]
  ]))

/** `akua.lock` as written to disk. */
export const formatLock = (lock: Lock, cli: string) => `${lockHeader(cli)}${lockBody(lock)}`

/** A dependency as resolution pinned it. */
export interface LockUpdate {
  readonly name: string
  readonly version: string
  readonly source: string
  readonly digest: string
  readonly replaced: Option.Option<string>
  /** The signature resolution verified for `digest`; none keeps what the lock recorded for it. */
  readonly signature: Option.Option<string>
  /** A CRD dependency's generated tree digest; none for other dependencies. */
  readonly crdsDigest: Option.Option<string>
}

/**
 * Upsert each update by name, sorted: a dependency resolved at another
 * version replaces its old entry. An entry whose digest is unchanged keeps
 * what is tied to those bytes (signature, attestation, vendor digest,
 * edges); a new digest drops it. A signature resolution just verified
 * replaces the recorded one.
 */
export const mergeIntoLock = (lock: Lock, updates: ReadonlyArray<LockUpdate>): Lock => {
  const renamed = new Set(updates.map((update) => update.name))
  const packages = (lock.package ?? []).filter((entry) =>
    !renamed.has(entry.name) || updates.some((update) => update.name === entry.name && update.version === entry.version)
  )
  for (const update of updates) {
    const slot = packages.findIndex((entry) => entry.name === update.name && entry.version === update.version)
    const previous = packages[slot]
    const carry = previous !== undefined && previous.digest === update.digest ? previous : undefined
    const entry: LockedPackage = {
      name: update.name,
      version: update.version,
      source: update.source,
      digest: update.digest,
      ...(carry?.vendor_digest === undefined ? {} : { vendor_digest: carry.vendor_digest }),
      ...Option.match(Option.orElse(update.signature, () => Option.fromUndefinedOr(carry?.signature)), {
        onNone: () => ({}),
        onSome: (signature) => ({ signature })
      }),
      ...(carry?.dependencies === undefined ? {} : { dependencies: carry.dependencies }),
      ...(carry?.attestation === undefined ? {} : { attestation: carry.attestation }),
      ...Option.match(update.replaced, { onNone: () => ({}), onSome: (path) => ({ replaced: { path } }) }),
      ...(carry?.yanked === undefined ? {} : { yanked: carry.yanked }),
      ...(carry?.kyverno_source_digest === undefined ? {} : { kyverno_source_digest: carry.kyverno_source_digest }),
      ...(carry?.converter_version === undefined ? {} : { converter_version: carry.converter_version }),
      ...Option.match(update.crdsDigest, { onNone: () => ({}), onSome: (crds_digest) => ({ crds_digest }) })
    }
    if (slot === -1) packages.push(entry)
    else packages[slot] = entry
  }
  return { version: lock.version, package: packages.toSorted(byNameThenVersion) }
}
