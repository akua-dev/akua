import { Effect, FileSystem, Option, Path, Schema } from "effect"
import * as TOML from "smol-toml"
import { CRD_CONVERTER_VERSION, CrdsInvalid } from "./crd-schemas"
import { kclIdent } from "./manifest"
import { loadSnapshot, type Snapshot, treeDigest } from "./snapshot.effect"
import { table, toToml } from "./toml-write"

/**
 * The generated CRD schemas a Package keeps beside its manifest:
 * `.akua/crds/` is the KCL package `crds`, one directory per CRD dependency
 * (`.akua/crds/<ident>/<group>/<version>/<kind>.k`), each with a
 * `source.toml` naming what it was generated from. `add`, `lock` and
 * `update` write it; a render uses a directory only while its
 * `source.toml` still matches `akua.toml` and `akua.lock`, so a committed
 * tree renders offline and never goes stale silently.
 */

export const CRDS_DIR = ".akua/crds"
export const PROVENANCE_FILE = "source.toml"
export const CRDS_KCL_MOD = "[package]\nname = \"crds\"\nedition = \"0.0.1\"\nversion = \"0.0.1\"\n"

const encoder = new TextEncoder()
const decoder = new TextDecoder()

const Provenance = Schema.Struct({
  dependency: Schema.String,
  /** The source as `akua.lock` records it. */
  source: Schema.String,
  /** The version as `akua.lock` records it. */
  version: Schema.String,
  /** The `crds` selector. */
  crds: Schema.String,
  digest: Schema.String,
  converter: Schema.String
})
export type Provenance = typeof Provenance.Type

const decodeProvenance = Schema.decodeUnknownEffect(Provenance)

export const provenanceToml = (provenance: Provenance) =>
  "# Generated by akuapkg from the CustomResourceDefinitions of a dependency. Do not edit:\n" +
  "# `akuapkg lock` regenerates this directory.\n\n" +
  toToml(table([
    ["dependency", provenance.dependency],
    ["source", provenance.source],
    ["version", provenance.version],
    ["crds", provenance.crds],
    ["digest", provenance.digest],
    ["converter", provenance.converter]
  ]))

/**
 * A dependency's generated directory, if one exists: its files (keyed
 * relative to it) and its provenance. A directory without a readable
 * `source.toml` is not a generated tree and is ignored.
 */
export const readGeneratedCrds = Effect.fn("readGeneratedCrds")(function*(workspace: string, dependency: string) {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const directory = path.join(workspace, CRDS_DIR, kclIdent(dependency))
  const exists = yield* fs.exists(path.join(directory, PROVENANCE_FILE)).pipe(Effect.orElseSucceed(() => false))
  if (!exists) return Option.none()
  const files = yield* loadSnapshot(directory)
  const provenance = yield* Effect.try({
    try: (): unknown => TOML.parse(decoder.decode(files.get(PROVENANCE_FILE) ?? new Uint8Array())),
    catch: (cause) => new CrdsInvalid({ message: `${directory}/${PROVENANCE_FILE}: ${String(cause)}` })
  }).pipe(
    Effect.flatMap(decodeProvenance),
    Effect.mapError((error) =>
      error._tag === "CrdsInvalid" ? error : new CrdsInvalid({ message: `${directory}/${PROVENANCE_FILE}: ${error.message}` })
    )
  )
  return Option.some({ directory, files, provenance })
})

/** One dependency's tree to write: the generated schemas and where they came from. */
export interface GeneratedCrds {
  readonly dependency: string
  readonly files: Snapshot
  readonly provenance: Omit<Provenance, "converter">
}

/**
 * Write `.akua/crds/` for `trees`: each dependency's directory is replaced
 * when its content changed. With `prune`, `trees` is every CRD dependency:
 * directories of others are removed (only generated ones, recognised by
 * `source.toml`), and the whole directory goes when none is left.
 */
export const writeGeneratedCrds = Effect.fn("writeGeneratedCrds")(function*(
  workspace: string,
  trees: ReadonlyArray<GeneratedCrds>,
  prune = true
) {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const root = path.join(workspace, CRDS_DIR)
  const wanted = new Map(trees.map((tree) => [kclIdent(tree.dependency), tree]))
  const existing = prune && (yield* fs.exists(root)) ? yield* fs.readDirectory(root) : []
  for (const name of existing) {
    if (wanted.has(name)) continue
    const generated = yield* fs.stat(path.join(root, name, PROVENANCE_FILE)).pipe(
      Effect.map((info) => info.type === "File"),
      Effect.orElseSucceed(() => false)
    )
    if (generated) yield* fs.remove(path.join(root, name), { recursive: true })
  }
  if (trees.length === 0) {
    if (!prune) return
    if ((yield* fs.exists(root)) && (yield* fs.readDirectory(root)).every((name) => name === "kcl.mod")) {
      yield* fs.remove(root, { recursive: true })
    }
    return
  }
  yield* fs.makeDirectory(root, { recursive: true })
  yield* fs.writeFileString(path.join(root, "kcl.mod"), CRDS_KCL_MOD)
  for (const [ident, tree] of wanted) {
    const directory = path.join(root, ident)
    const files = withProvenance(tree)
    if (yield* fs.exists(directory)) {
      const current = yield* loadSnapshot(directory)
      if (sameFiles(current, files)) continue
      yield* fs.remove(directory, { recursive: true })
    }
    for (const [name, data] of files) {
      const target = path.join(directory, ...name.split("/"))
      yield* fs.makeDirectory(path.dirname(target), { recursive: true })
      yield* fs.writeFile(target, data)
    }
  }
})

/**
 * The digest `akua.lock` records for a dependency's generated directory
 * (`crds_digest`): every file `lock` writes there, `source.toml` included.
 * A render uses the directory only while it still has this digest.
 */
export const generatedCrdsDigest = (tree: GeneratedCrds) => treeDigest(withProvenance(tree))

/** A dependency's directory as written: its schemas and `source.toml`. */
const withProvenance = (tree: GeneratedCrds): Snapshot =>
  new Map(tree.files).set(
    PROVENANCE_FILE,
    encoder.encode(provenanceToml({ ...tree.provenance, converter: CRD_CONVERTER_VERSION }))
  )

/**
 * The dependencies whose directory under `.akua/crds/` is missing or not
 * byte-identical to what `writeGeneratedCrds` would write for `trees`.
 */
export const staleGeneratedCrds = Effect.fn("staleGeneratedCrds")(function*(
  workspace: string,
  trees: ReadonlyArray<GeneratedCrds>
) {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const stale: Array<string> = []
  for (const tree of trees) {
    const directory = path.join(workspace, CRDS_DIR, kclIdent(tree.dependency))
    const current = (yield* fs.exists(directory)) ? yield* loadSnapshot(directory) : new Map<string, Uint8Array>()
    if (!sameFiles(current, withProvenance(tree))) stale.push(tree.dependency)
  }
  return stale
})

const sameFiles = (a: Snapshot, b: Snapshot) =>
  a.size === b.size && Array.from(a).every(([name, data]) => {
    const other = b.get(name)
    return other !== undefined && other.length === data.length && data.every((byte, index) => byte === other[index])
  })
